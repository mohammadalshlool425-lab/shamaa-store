def extract_year(text: str) -> Optional[int]:
    """يستخرج سنة الموديل من نص الإعلان (يدعم 2016 و 16 و صيغ شائعة)."""
    if not text:
        return None
    m = re.search(r"(19[6-9]\d|20[0-4]\d)", text)
    if m:
        return int(m.group(1))
    # صيغة "موديل 16" أو "ريو 16"
    m = re.search(r"(?:موديل|model|طراز)\s*[:\-]?\s*(\d{2})\b", text, re.I)
    if m:
        yy = int(m.group(1))
        return 2000 + yy if yy <= 30 else 1900 + yy
    return None


def _retained(age: int, curve=None) -> float:
    """نسبة القيمة المتبقية لسلعة عمرها `age` سنة من جديد."""
    curve = curve or DEPRECIATION_CURVE
    if age <= 0:
        return 1.0
    for limit, factor in curve:
        if age <= limit:
            return factor
    return curve[-1][1]


def year_factor(year: Optional[int], curve=None, anchor_base: float = None) -> Optional[float]:
    """
    معامل سنة الموديل.
    = (ما تبقّى من قيمة السلعة اليوم) ÷ (ما تبقّى من قيمة موديل المعايرة اليوم)
    بهذه الطريقة تبقى الأرقام مطلقة وقابلة للمقارنة بسعر السوق الفعلي.
    """
    if year is None:
        return None
    age = max(0, CURRENT_YEAR - year)
    return round(_retained(age, curve) / (anchor_base or _ANCHOR_BASE), 3)


# نسبة الخصم الإضافية عندما يقبل البائع المقايضة (يوسّع دائرة المشترين
# لكنه عادةً يقبل سعراً أدنى نقدياً)
BARTER_DISCOUNT = 0.07


def _best_match(text: str, table: Dict[str, float], base: float):
    """أطول كلمة مطابقة تفوز — لأنها الأكثر تحديداً. يعيد None إن لم يطابق شيء."""
    best, best_len = None, 0
    for kw, value in table.items():
        if kw.lower() in text:
            # الأرقام المطلقة (مثل أسعار الهواتف) تُحوَّل إلى معامل نسبةً للأساس
            factor = value / base if value > 3 else float(value)
            if len(kw) > best_len:
                best, best_len = factor, len(kw)
    return best


def _keyword_multiplier(name: str, cat_cfg: Dict[str, Any]) -> float:
    """
    معامل السعر من نص الإعلان.
    السيارات: ماركة × موديل (هيونداي توسان ≠ هيونداي i10).
    بقية الفئات: أطول كلمة مفتاحية مطابقة.
    """
    text = (name or "").lower()
    base = cat_cfg["base"]
    # الموديل المحدد أدق دائماً من اسم الماركة: "مرسيدس C200" تُسعَّر كـ C200
    # لا كـ "مرسيدس" عامة، ولا يُضرب الاثنان معاً.
    model = _best_match(text, cat_cfg.get("keywords", {}), base)
    if model is not None:
        return model
    return _best_match(text, cat_cfg.get("brand_factors", {}), base) or 1.0


def estimate_price(item_name: str, category: str, condition: int,
                   city: str = "عمّان", accepts_barter: bool = False) -> Dict[str, Any]:
    """
    يعيد: السعر العادل + نطاق المفاوضة + سعر البيع السريع + تحليل العوامل.
    """
    cat_cfg = CATEGORY_BASE.get(category) or CATEGORY_BASE["أخرى"]
    condition = max(1, min(10, int(condition)))

    kw_mult = _keyword_multiplier(item_name, cat_cfg)
    cond_mult = CONDITION_FACTOR[condition]
    city_mult = CITY_FACTOR.get((city or "عمّان").strip(), 0.88)

    uses_year = bool(cat_cfg.get("uses_year"))
    year = extract_year(item_name) if uses_year else None
    if uses_year:
        # السيارات تستخدم منحنى الإهلاك المخفَّف الخاص بالسوق الأردني
        is_car = category == "سيارات"
        yr_mult = year_factor(
            year,
            CAR_DEPRECIATION_CURVE if is_car else None,
            _CAR_ANCHOR_BASE if is_car else None,
        )
    else:
        yr_mult = None

    base = cat_cfg["base"] * kw_mult
    fair = base * cond_mult * city_mult
    if yr_mult:
        fair *= yr_mult
    if accepts_barter:
        fair *= (1 - BARTER_DISCOUNT)

    fair = max(1.0, round(fair))
    spread = cat_cfg["spread"]

    # نطاق المفاوضة: السوق الأردني يفاوض بقوة على المستعمل
    low = max(1.0, round(fair * (1 - spread * 0.28)))
    high = round(fair * (1 + spread * 0.22))
    quick_sale = max(1.0, round(fair * 0.84))   # سعر "يبيع خلال 48 ساعة"

    # شرح العوامل للمستخدم (يبني الثقة في الرقم)
    drivers = []
    if kw_mult != 1.0:
        drivers.append(f"تم التعرف على السلعة في السوق الأردني (معامل {kw_mult:.2f}× عن متوسط الفئة)")
    else:
        drivers.append("لم يتم التعرف على نوع محدد — استُخدم متوسط الفئة")
    if yr_mult:
        drivers.append(f"موديل {year} — تبقّى {yr_mult:.0%} من قيمته بعد الإهلاك (السوق الأردني)")
    elif cat_cfg.get("uses_year"):
        drivers.append("لم يُذكر موديل/سنة — لم يُطبَّق معامل الإهلاك (اذكر السنة لدقة أعلى)")
    drivers.append(f"حالة المنتج {condition}/10 تعادل {cond_mult:.0%} من قيمة الجديد")
    drivers.append(f"مستوى الطلب في {city or 'عمّان'}: {city_mult:.2f}×")
    if accepts_barter:
        drivers.append(f"قبول المقايضة يخفض السعر النقدي {BARTER_DISCOUNT:.0%} لكنه يضاعف عدد المهتمين")

    # نصيحة بيع
    if condition >= 9:
        tip = "سلعتك بحالة ممتازة — لا تنشر بأقل من الحد الأعلى، وارفق 4 صور واضحة على الأقل."
    elif condition >= 6:
        tip = f"انشر بـ {high} دينار وتوقع مفاوضات حتى {low}. اذكر أي عيوب بصراحة لتسريع البيع."
    else:
        tip = f"الحالة متواضعة — أفضل استراتيجية هي النشر بـ {quick_sale} دينار مع قبول المقايضة."

    return {
        "fair_price": fair,
        "low_price": low,
        "high_price": high,
        "quick_sale_price": quick_sale,
        "currency": "د.أ",
        "category": category,
        "condition": condition,
        "city": city or "عمّان",
        "accepts_barter": accepts_barter,
        "drivers": drivers,
        "tip": tip,
    }


def pricing_credits_needed(uses_today: int, free_daily: int = 3) -> bool:
    """هل يحتاج المستخدم رصيداً مدفوعاً لإجراء تسعير جديد؟"""
    return uses_today >= free_daily
