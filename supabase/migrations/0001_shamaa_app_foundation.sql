CREATE TABLE shamaa_app.mail_outbox (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  recipient TEXT NOT NULL,
  subject TEXT NOT NULL,
  body TEXT NOT NULL,
  html TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','sending','sent','file','failed')),
  attempts INTEGER NOT NULL DEFAULT 0,
  available_at BIGINT NOT NULL,
  created_at BIGINT NOT NULL,
  sent_at BIGINT,
  last_error TEXT NOT NULL DEFAULT ''
);

CREATE OR REPLACE FUNCTION shamaa_app.reject_immutable_change()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog
AS $$
BEGIN
  RAISE EXCEPTION 'append-only table: mutation rejected';
END;
$$;

CREATE TRIGGER immutable_audit_update BEFORE UPDATE OR DELETE ON shamaa_app.audit_log
  FOR EACH ROW EXECUTE FUNCTION shamaa_app.reject_immutable_change();
CREATE TRIGGER immutable_ledger_update BEFORE UPDATE OR DELETE ON shamaa_app.ledger
  FOR EACH ROW EXECUTE FUNCTION shamaa_app.reject_immutable_change();
CREATE TRIGGER immutable_events_update BEFORE UPDATE OR DELETE ON shamaa_app.order_events
  FOR EACH ROW EXECUTE FUNCTION shamaa_app.reject_immutable_change();
CREATE TRIGGER immutable_inventory_update BEFORE UPDATE OR DELETE ON shamaa_app.inventory_movements
  FOR EACH ROW EXECUTE FUNCTION shamaa_app.reject_immutable_change();

-- Fail closed: no Data API exposure and no row access until reviewed policies
-- and a dedicated NOBYPASSRLS runtime role are installed in the next migration.
DO $$
DECLARE t TEXT;
BEGIN
  FOREACH t IN ARRAY ARRAY[
    'users','sessions','auth_tokens','rate_limits','categories','stores','media',
    'products','carts','orders','seller_orders','order_items','order_events',
    'inventory_movements','ledger','notifications','audit_log','settings','mail_outbox'
  ] LOOP
    EXECUTE format('ALTER TABLE shamaa_app.%I ENABLE ROW LEVEL SECURITY',t);
    EXECUTE format('ALTER TABLE shamaa_app.%I FORCE ROW LEVEL SECURITY',t);
  END LOOP;
END $$;

COMMIT;
