-- SHAM'A application schema for the existing FastAPI domain model.
-- Apply only to a dedicated Supabase project after reviewing this migration.
-- This migration intentionally does not modify public.* or Supabase Auth.
-- All money is integer fils (1 JOD = 1000 fils); timestamps are Unix seconds.

BEGIN;

CREATE SCHEMA IF NOT EXISTS shamaa_app;
REVOKE ALL ON SCHEMA shamaa_app FROM PUBLIC;
COMMENT ON SCHEMA shamaa_app IS
  'Private application schema. Not exposed through Supabase Data API. FastAPI server only.';

CREATE TABLE shamaa_app.users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL DEFAULT 'buyer' CHECK (role IN ('buyer','seller','admin')),
  locale TEXT NOT NULL DEFAULT 'ar' CHECK (locale IN ('ar','en')),
  active BOOLEAN NOT NULL DEFAULT TRUE,
  email_verified_at BIGINT,
  mfa_secret TEXT,
  mfa_last_step BIGINT NOT NULL DEFAULT 0,
  created_at BIGINT NOT NULL
);
CREATE UNIQUE INDEX users_email_lower_unique ON shamaa_app.users (lower(email));

CREATE TABLE shamaa_app.sessions (
  token_hash TEXT PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES shamaa_app.users(id),
  csrf_token TEXT NOT NULL,
  created_at BIGINT NOT NULL,
  expires_at BIGINT NOT NULL,
  ip_hash TEXT NOT NULL,
  user_agent TEXT NOT NULL,
  mfa_at BIGINT
);
CREATE INDEX sessions_user ON shamaa_app.sessions(user_id);

CREATE TABLE shamaa_app.auth_tokens (
  token_hash TEXT PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES shamaa_app.users(id),
  purpose TEXT NOT NULL CHECK (purpose IN ('verify','reset')),
  expires_at BIGINT NOT NULL,
  used_at BIGINT
);

CREATE TABLE shamaa_app.rate_limits (
  bucket TEXT PRIMARY KEY,
  window_start BIGINT NOT NULL,
  count BIGINT NOT NULL CHECK (count >= 0)
);

CREATE TABLE shamaa_app.categories (
  id TEXT PRIMARY KEY,
  name_ar TEXT NOT NULL,
  name_en TEXT NOT NULL,
  icon TEXT NOT NULL,
  parent_id TEXT REFERENCES shamaa_app.categories(id),
  commission_bps INTEGER CHECK (commission_bps BETWEEN 0 AND 5000)
);

CREATE TABLE shamaa_app.stores (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id BIGINT NOT NULL UNIQUE REFERENCES shamaa_app.users(id),
  slug TEXT NOT NULL UNIQUE,
  name_ar TEXT NOT NULL,
  name_en TEXT NOT NULL,
  description_ar TEXT NOT NULL DEFAULT '',
  description_en TEXT NOT NULL DEFAULT '',
  city TEXT NOT NULL,
  accent TEXT NOT NULL DEFAULT 'green' CHECK (accent IN ('green','sand','blue')),
  shipping_fils BIGINT NOT NULL DEFAULT 3000 CHECK (shipping_fils BETWEEN 0 AND 100000),
  delivery_days INTEGER NOT NULL DEFAULT 3 CHECK (delivery_days BETWEEN 1 AND 30),
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','active','rejected','suspended')),
  review_note TEXT NOT NULL DEFAULT '',
  commission_bps INTEGER CHECK (commission_bps BETWEEN 0 AND 5000),
  is_demo BOOLEAN NOT NULL DEFAULT FALSE,
  created_at BIGINT NOT NULL
);

CREATE TABLE shamaa_app.media (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id BIGINT NOT NULL REFERENCES shamaa_app.users(id),
  digest TEXT NOT NULL,
  storage_key TEXT NOT NULL UNIQUE,
  bytes BIGINT NOT NULL CHECK (bytes > 0),
  created_at BIGINT NOT NULL,
  UNIQUE(owner_id,digest)
);

CREATE TABLE shamaa_app.products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  store_id BIGINT NOT NULL REFERENCES shamaa_app.stores(id),
  category_id TEXT NOT NULL REFERENCES shamaa_app.categories(id),
  title_ar TEXT NOT NULL,
  title_en TEXT NOT NULL,
  description_ar TEXT NOT NULL,
  description_en TEXT NOT NULL,
  price_fils BIGINT NOT NULL CHECK (price_fils BETWEEN 1 AND 1000000000),
  compare_at_fils BIGINT CHECK (compare_at_fils IS NULL OR compare_at_fils > price_fils),
  stock INTEGER NOT NULL CHECK (stock BETWEEN 0 AND 1000000),
  sku TEXT NOT NULL,
  media_id BIGINT REFERENCES shamaa_app.media(id),
  demo_image TEXT,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('draft','pending','active','paused','rejected')),
  review_note TEXT NOT NULL DEFAULT '',
  featured BOOLEAN NOT NULL DEFAULT FALSE,
  version BIGINT NOT NULL DEFAULT 1,
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL,
  UNIQUE(store_id,sku)
);
CREATE INDEX products_catalog ON shamaa_app.products(status,category_id,price_fils);
CREATE INDEX products_store ON shamaa_app.products(store_id,status);

CREATE TABLE shamaa_app.carts (
  user_id BIGINT NOT NULL REFERENCES shamaa_app.users(id),
  product_id BIGINT NOT NULL REFERENCES shamaa_app.products(id),
  quantity INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 99),
  PRIMARY KEY(user_id,product_id)
);

CREATE TABLE shamaa_app.orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  number TEXT NOT NULL UNIQUE,
  buyer_id BIGINT NOT NULL REFERENCES shamaa_app.users(id),
  idempotency_key TEXT NOT NULL,
  request_hash TEXT NOT NULL,
  recipient TEXT NOT NULL,
  phone TEXT NOT NULL,
  city TEXT NOT NULL,
  address TEXT NOT NULL,
  subtotal_fils BIGINT NOT NULL CHECK (subtotal_fils >= 0),
  shipping_fils BIGINT NOT NULL CHECK (shipping_fils >= 0),
  total_fils BIGINT NOT NULL CHECK (total_fils = subtotal_fils + shipping_fils),
  payment_method TEXT NOT NULL DEFAULT 'cod' CHECK (payment_method = 'cod'),
  is_demo BOOLEAN NOT NULL DEFAULT FALSE,
  created_at BIGINT NOT NULL,
  UNIQUE(buyer_id,idempotency_key)
);

CREATE TABLE shamaa_app.seller_orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES shamaa_app.orders(id),
  store_id BIGINT NOT NULL REFERENCES shamaa_app.stores(id),
  status TEXT NOT NULL DEFAULT 'new' CHECK (status IN ('new','confirmed','preparing','shipped','delivered','cancelled')),
  subtotal_fils BIGINT NOT NULL,
  shipping_fils BIGINT NOT NULL,
  commission_fils BIGINT NOT NULL,
  net_fils BIGINT NOT NULL CHECK (net_fils = subtotal_fils + shipping_fils - commission_fils),
  updated_at BIGINT NOT NULL,
  UNIQUE(order_id,store_id)
);

CREATE TABLE shamaa_app.order_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  seller_order_id BIGINT NOT NULL REFERENCES shamaa_app.seller_orders(id),
  product_id BIGINT NOT NULL REFERENCES shamaa_app.products(id),
  title_ar TEXT NOT NULL,
  title_en TEXT NOT NULL,
  unit_price_fils BIGINT NOT NULL,
  quantity INTEGER NOT NULL CHECK (quantity > 0),
  commission_bps INTEGER NOT NULL CHECK (commission_bps BETWEEN 0 AND 5000),
  commission_fils BIGINT NOT NULL,
  image_url TEXT NOT NULL,
  UNIQUE(seller_order_id,product_id)
);

CREATE TABLE shamaa_app.order_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  seller_order_id BIGINT NOT NULL REFERENCES shamaa_app.seller_orders(id),
  actor_id BIGINT NOT NULL REFERENCES shamaa_app.users(id),
  from_status TEXT,
  to_status TEXT NOT NULL,
  note TEXT NOT NULL DEFAULT '',
  created_at BIGINT NOT NULL
);

CREATE TABLE shamaa_app.inventory_movements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id BIGINT NOT NULL REFERENCES shamaa_app.products(id),
  actor_id BIGINT NOT NULL REFERENCES shamaa_app.users(id),
  delta INTEGER NOT NULL,
  reason TEXT NOT NULL,
  seller_order_id BIGINT REFERENCES shamaa_app.seller_orders(id),
  created_at BIGINT NOT NULL,
  UNIQUE(product_id,seller_order_id,reason)
);

CREATE TABLE shamaa_app.ledger (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  seller_order_id BIGINT NOT NULL REFERENCES shamaa_app.seller_orders(id),
  store_id BIGINT NOT NULL REFERENCES shamaa_app.stores(id),
  kind TEXT NOT NULL CHECK (kind = 'cod_commission_due'),
  amount_fils BIGINT NOT NULL CHECK (amount_fils >= 0),
  created_at BIGINT NOT NULL,
  UNIQUE(seller_order_id,kind)
);

CREATE TABLE shamaa_app.notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES shamaa_app.users(id),
  kind TEXT NOT NULL,
  body_ar TEXT NOT NULL,
  body_en TEXT NOT NULL,
  read_at BIGINT,
  created_at BIGINT NOT NULL
);
CREATE INDEX notifications_user ON shamaa_app.notifications(user_id,created_at);

CREATE TABLE shamaa_app.audit_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id BIGINT REFERENCES shamaa_app.users(id),
  action TEXT NOT NULL,
  entity TEXT NOT NULL,
  entity_id TEXT NOT NULL,
  detail TEXT NOT NULL DEFAULT '',
  created_at BIGINT NOT NULL
);

CREATE TABLE shamaa_app.settings (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);
