-- SHAM'A phase 2, batch 2: private product image gallery; no Data API access.
BEGIN;
CREATE TABLE shamaa_app.product_images (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id BIGINT NOT NULL REFERENCES shamaa_app.products(id) ON DELETE CASCADE,
  media_id BIGINT NOT NULL REFERENCES shamaa_app.media(id),
  position INTEGER NOT NULL CHECK (position BETWEEN 0 AND 7),
  created_at BIGINT NOT NULL,
  UNIQUE(product_id,media_id),
  UNIQUE(product_id,position)
);
INSERT INTO shamaa_app.product_images(product_id,media_id,position,created_at)
SELECT id,media_id,0,created_at FROM shamaa_app.products WHERE media_id IS NOT NULL;
ALTER TABLE shamaa_app.product_images ENABLE ROW LEVEL SECURITY;
ALTER TABLE shamaa_app.product_images FORCE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE shamaa_app.product_images FROM PUBLIC, anon, authenticated, service_role;
COMMIT;
