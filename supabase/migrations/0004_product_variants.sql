-- SHAM'A phase 2, batch 3: variant-specific SKU, price and stock.
-- Carts and order lines can now distinguish several variants of one product.
-- RLS remains closed; no runtime role or Data API grants are introduced.
BEGIN;

CREATE TABLE shamaa_app.product_variants (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id BIGINT NOT NULL REFERENCES shamaa_app.products(id) ON DELETE CASCADE,
  store_id BIGINT NOT NULL REFERENCES shamaa_app.stores(id),
  sku TEXT NOT NULL,
  attributes_json TEXT NOT NULL,
  price_fils BIGINT NOT NULL CHECK (price_fils BETWEEN 1 AND 1000000000),
  compare_at_fils BIGINT CHECK (compare_at_fils IS NULL OR compare_at_fils > price_fils),
  stock INTEGER NOT NULL CHECK (stock BETWEEN 0 AND 1000000),
  active BOOLEAN NOT NULL DEFAULT TRUE,
  version BIGINT NOT NULL DEFAULT 1,
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL,
  UNIQUE(product_id,sku),
  UNIQUE(store_id,sku),
  UNIQUE(product_id,attributes_json)
);
CREATE INDEX product_variants_active ON shamaa_app.product_variants(product_id,active,price_fils);

ALTER TABLE shamaa_app.carts
  ADD COLUMN variant_id BIGINT REFERENCES shamaa_app.product_variants(id),
  ADD COLUMN variant_key BIGINT NOT NULL DEFAULT 0;
ALTER TABLE shamaa_app.carts DROP CONSTRAINT carts_pkey;
ALTER TABLE shamaa_app.carts ADD CONSTRAINT carts_variant_key_check
  CHECK (variant_key=COALESCE(variant_id,0));
ALTER TABLE shamaa_app.carts ADD PRIMARY KEY(user_id,product_id,variant_key);

ALTER TABLE shamaa_app.order_items
  ADD COLUMN variant_id BIGINT REFERENCES shamaa_app.product_variants(id),
  ADD COLUMN variant_key BIGINT NOT NULL DEFAULT 0,
  ADD COLUMN variant_sku TEXT NOT NULL DEFAULT '',
  ADD COLUMN variant_attributes TEXT NOT NULL DEFAULT '{}';
ALTER TABLE shamaa_app.order_items
  DROP CONSTRAINT order_items_seller_order_id_product_id_key;
ALTER TABLE shamaa_app.order_items
  ADD CONSTRAINT order_items_variant_key_check
  CHECK (variant_key=COALESCE(variant_id,0));
ALTER TABLE shamaa_app.order_items
  ADD CONSTRAINT order_items_product_variant_unique
  UNIQUE(seller_order_id,product_id,variant_key);

ALTER TABLE shamaa_app.product_variants ENABLE ROW LEVEL SECURITY;
ALTER TABLE shamaa_app.product_variants FORCE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE shamaa_app.product_variants FROM PUBLIC;

COMMIT;
