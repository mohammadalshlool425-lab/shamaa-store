-- SHAM'A phase 2, batch 4: order-scoped private text conversations.
-- Participants derive from the underlying order and store; RLS remains fail-closed.
BEGIN;

CREATE TABLE shamaa_app.conversations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  seller_order_id BIGINT NOT NULL UNIQUE
    REFERENCES shamaa_app.seller_orders(id) ON DELETE RESTRICT,
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL
);
CREATE INDEX conversations_seller_order
  ON shamaa_app.conversations(seller_order_id,updated_at);

CREATE TABLE shamaa_app.messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation_id BIGINT NOT NULL
    REFERENCES shamaa_app.conversations(id) ON DELETE RESTRICT,
  sender_id BIGINT NOT NULL
    REFERENCES shamaa_app.users(id) ON DELETE RESTRICT,
  client_key TEXT NOT NULL CHECK (char_length(client_key) BETWEEN 16 AND 80),
  body TEXT NOT NULL CHECK (char_length(body) BETWEEN 1 AND 4000),
  body_hash TEXT NOT NULL CHECK (char_length(body_hash)=64),
  created_at BIGINT NOT NULL,
  UNIQUE(conversation_id,sender_id,client_key)
);
CREATE INDEX messages_conversation_created
  ON shamaa_app.messages(conversation_id,id);

CREATE OR REPLACE FUNCTION shamaa_app.require_conversation_participant()
RETURNS trigger
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = pg_catalog, shamaa_app
AS $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
      FROM shamaa_app.conversations c
      JOIN shamaa_app.seller_orders so ON so.id=c.seller_order_id
      JOIN shamaa_app.orders o ON o.id=so.order_id
      JOIN shamaa_app.stores s ON s.id=so.store_id
     WHERE c.id=NEW.conversation_id
       AND (o.buyer_id=NEW.sender_id OR s.owner_id=NEW.sender_id)
  ) THEN
    RAISE EXCEPTION 'message sender is not a conversation participant'
      USING ERRCODE='42501';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER messages_sender_participant
  BEFORE INSERT ON shamaa_app.messages
  FOR EACH ROW EXECUTE FUNCTION shamaa_app.require_conversation_participant();

CREATE TRIGGER immutable_messages_update
  BEFORE UPDATE OR DELETE ON shamaa_app.messages
  FOR EACH ROW EXECUTE FUNCTION shamaa_app.reject_immutable_change();

ALTER TABLE shamaa_app.conversations ENABLE ROW LEVEL SECURITY;
ALTER TABLE shamaa_app.conversations FORCE ROW LEVEL SECURITY;
ALTER TABLE shamaa_app.messages ENABLE ROW LEVEL SECURITY;
ALTER TABLE shamaa_app.messages FORCE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE shamaa_app.conversations FROM PUBLIC;
REVOKE ALL ON TABLE shamaa_app.messages FROM PUBLIC;

COMMIT;
