-- SHAM'A phase 2, batch 5: verified reviews tied to delivered order items.
-- Moderation is explicit; reports never hide reviews automatically. RLS stays closed.
BEGIN;

CREATE TABLE shamaa_app.reviews (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_item_id BIGINT NOT NULL UNIQUE REFERENCES shamaa_app.order_items(id) ON DELETE RESTRICT,
 buyer_id BIGINT NOT NULL REFERENCES shamaa_app.users(id) ON DELETE RESTRICT,
 product_id BIGINT NOT NULL REFERENCES shamaa_app.products(id) ON DELETE RESTRICT,
 seller_order_id BIGINT NOT NULL REFERENCES shamaa_app.seller_orders(id) ON DELETE RESTRICT,
 rating SMALLINT NOT NULL CHECK(rating BETWEEN 1 AND 5),
 body TEXT NOT NULL DEFAULT '' CHECK(char_length(body)<=2000),
 status TEXT NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','approved','rejected')),
 moderation_note TEXT NOT NULL DEFAULT '',
 moderated_by BIGINT REFERENCES shamaa_app.users(id) ON DELETE RESTRICT,
 moderated_at BIGINT,
 created_at BIGINT NOT NULL,
 updated_at BIGINT NOT NULL,
 CHECK((status='pending' AND moderated_by IS NULL AND moderated_at IS NULL)
    OR (status IN ('approved','rejected') AND moderated_by IS NOT NULL AND moderated_at IS NOT NULL))
);
CREATE INDEX reviews_product_public ON shamaa_app.reviews(product_id,status,created_at DESC,id DESC);
CREATE INDEX reviews_queue ON shamaa_app.reviews(status,created_at,id);

CREATE TABLE shamaa_app.review_reports (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 review_id BIGINT NOT NULL REFERENCES shamaa_app.reviews(id) ON DELETE RESTRICT,
 reporter_id BIGINT NOT NULL REFERENCES shamaa_app.users(id) ON DELETE RESTRICT,
 reason TEXT NOT NULL CHECK(reason IN ('incorrect','personal_data','abuse','other')),
 details TEXT NOT NULL DEFAULT '' CHECK(char_length(details)<=500),
 status TEXT NOT NULL DEFAULT 'open' CHECK(status IN ('open','resolved','dismissed')),
 resolution_note TEXT NOT NULL DEFAULT '',
 resolved_by BIGINT REFERENCES shamaa_app.users(id) ON DELETE RESTRICT,
 resolved_at BIGINT,
 created_at BIGINT NOT NULL,
 UNIQUE(review_id,reporter_id),
 CHECK((status='open' AND resolved_by IS NULL AND resolved_at IS NULL)
    OR (status IN ('resolved','dismissed') AND resolved_by IS NOT NULL AND resolved_at IS NOT NULL))
);
CREATE INDEX review_reports_queue ON shamaa_app.review_reports(status,created_at,id);

CREATE OR REPLACE FUNCTION shamaa_app.validate_review_purchase()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER
SET search_path=pg_catalog,shamaa_app AS $$
BEGIN
 IF NOT EXISTS (
   SELECT 1 FROM shamaa_app.order_items oi
   JOIN shamaa_app.seller_orders so ON so.id=oi.seller_order_id
   JOIN shamaa_app.orders o ON o.id=so.order_id
   WHERE oi.id=NEW.order_item_id AND oi.product_id=NEW.product_id
     AND oi.seller_order_id=NEW.seller_order_id
     AND o.buyer_id=NEW.buyer_id AND so.status='delivered'
 ) THEN
   RAISE EXCEPTION 'review requires buyer own delivered order item' USING ERRCODE='42501';
 END IF;
 RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION shamaa_app.reject_review_content_change()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER
SET search_path=pg_catalog,shamaa_app AS $$
BEGIN
 IF TG_OP='DELETE' THEN
   RAISE EXCEPTION 'review history cannot be deleted';
 END IF;
 IF ROW(NEW.order_item_id,NEW.buyer_id,NEW.product_id,NEW.seller_order_id,
        NEW.rating,NEW.body,NEW.created_at)
    IS DISTINCT FROM
    ROW(OLD.order_item_id,OLD.buyer_id,OLD.product_id,OLD.seller_order_id,
        OLD.rating,OLD.body,OLD.created_at) THEN
   RAISE EXCEPTION 'review purchase and content are immutable';
 END IF;
 RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION shamaa_app.require_review_moderator()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER
SET search_path=pg_catalog,shamaa_app AS $$
BEGIN
 IF OLD.status<>'pending' OR NEW.status NOT IN ('approved','rejected')
    OR NOT EXISTS(SELECT 1 FROM shamaa_app.users u
                   WHERE u.id=NEW.moderated_by AND u.role='admin' AND u.active=TRUE) THEN
   RAISE EXCEPTION 'only an administrator can moderate a pending review'
     USING ERRCODE='42501';
 END IF;
 RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION shamaa_app.require_review_report_not_author()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER
SET search_path=pg_catalog,shamaa_app AS $$
BEGIN
 IF EXISTS(SELECT 1 FROM shamaa_app.reviews r
           WHERE r.id=NEW.review_id AND r.buyer_id=NEW.reporter_id) THEN
   RAISE EXCEPTION 'review author cannot report own review' USING ERRCODE='42501';
 END IF;
 RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION shamaa_app.reject_review_report_change()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER
SET search_path=pg_catalog,shamaa_app AS $$
BEGIN
 IF TG_OP='DELETE' THEN
   RAISE EXCEPTION 'review report history cannot be deleted';
 END IF;
 IF ROW(NEW.review_id,NEW.reporter_id,NEW.reason,NEW.details,NEW.created_at)
    IS DISTINCT FROM
    ROW(OLD.review_id,OLD.reporter_id,OLD.reason,OLD.details,OLD.created_at) THEN
   RAISE EXCEPTION 'review report evidence is immutable';
 END IF;
 RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION shamaa_app.require_review_report_moderator()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER
SET search_path=pg_catalog,shamaa_app AS $$
BEGIN
 IF OLD.status<>'open' OR NEW.status NOT IN ('resolved','dismissed')
    OR NOT EXISTS(SELECT 1 FROM shamaa_app.users u
                   WHERE u.id=NEW.resolved_by AND u.role='admin' AND u.active=TRUE) THEN
   RAISE EXCEPTION 'only an administrator can resolve an open review report'
     USING ERRCODE='42501';
 END IF;
 RETURN NEW;
END;
$$;

CREATE TRIGGER review_purchase_eligibility
 BEFORE INSERT ON shamaa_app.reviews
 FOR EACH ROW EXECUTE FUNCTION shamaa_app.validate_review_purchase();
CREATE TRIGGER review_content_immutable
 BEFORE UPDATE OR DELETE ON shamaa_app.reviews
 FOR EACH ROW EXECUTE FUNCTION shamaa_app.reject_review_content_change();
CREATE TRIGGER review_moderation_authority
 BEFORE UPDATE OF status,moderation_note,moderated_by,moderated_at ON shamaa_app.reviews
 FOR EACH ROW EXECUTE FUNCTION shamaa_app.require_review_moderator();
CREATE TRIGGER review_report_not_author
 BEFORE INSERT ON shamaa_app.review_reports
 FOR EACH ROW EXECUTE FUNCTION shamaa_app.require_review_report_not_author();
CREATE TRIGGER review_report_content_immutable
 BEFORE UPDATE OR DELETE ON shamaa_app.review_reports
 FOR EACH ROW EXECUTE FUNCTION shamaa_app.reject_review_report_change();
CREATE TRIGGER review_report_moderation_authority
 BEFORE UPDATE OF status,resolution_note,resolved_by,resolved_at ON shamaa_app.review_reports
 FOR EACH ROW EXECUTE FUNCTION shamaa_app.require_review_report_moderator();

ALTER TABLE shamaa_app.reviews ENABLE ROW LEVEL SECURITY;
ALTER TABLE shamaa_app.reviews FORCE ROW LEVEL SECURITY;
ALTER TABLE shamaa_app.review_reports ENABLE ROW LEVEL SECURITY;
ALTER TABLE shamaa_app.review_reports FORCE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE shamaa_app.reviews FROM PUBLIC;
REVOKE ALL ON TABLE shamaa_app.review_reports FROM PUBLIC;
REVOKE ALL ON FUNCTION shamaa_app.validate_review_purchase() FROM PUBLIC;
REVOKE ALL ON FUNCTION shamaa_app.reject_review_content_change() FROM PUBLIC;
REVOKE ALL ON FUNCTION shamaa_app.require_review_moderator() FROM PUBLIC;
REVOKE ALL ON FUNCTION shamaa_app.require_review_report_not_author() FROM PUBLIC;
REVOKE ALL ON FUNCTION shamaa_app.reject_review_report_change() FROM PUBLIC;
REVOKE ALL ON FUNCTION shamaa_app.require_review_report_moderator() FROM PUBLIC;

COMMIT;
