-- SHAM'A phase 2, batch 6: private shipment cases. No balance/refund side effects.
BEGIN;

CREATE TABLE shamaa_app.order_cases (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 seller_order_id BIGINT NOT NULL UNIQUE REFERENCES shamaa_app.seller_orders(id) ON DELETE RESTRICT,
 buyer_id BIGINT NOT NULL REFERENCES shamaa_app.users(id) ON DELETE RESTRICT,
 seller_id BIGINT NOT NULL REFERENCES shamaa_app.users(id) ON DELETE RESTRICT,
 reason TEXT NOT NULL CHECK(reason IN ('not_received','damaged','wrong_item','missing_item','not_as_described','other')),
 description TEXT NOT NULL CHECK(char_length(description) BETWEEN 20 AND 3000),
 status TEXT NOT NULL DEFAULT 'open' CHECK(status IN ('open','seller_responded','resolved','rejected')),
 opened_at BIGINT NOT NULL,
 response_due_at BIGINT NOT NULL,
 updated_at BIGINT NOT NULL,
 closed_at BIGINT,
 closed_by BIGINT REFERENCES shamaa_app.users(id) ON DELETE RESTRICT,
 resolution_note TEXT NOT NULL DEFAULT '',
 CHECK(response_due_at>=opened_at),
 CHECK(
   (status IN ('open','seller_responded') AND closed_at IS NULL AND closed_by IS NULL AND resolution_note='')
   OR
   (status IN ('resolved','rejected') AND closed_at IS NOT NULL AND closed_by IS NOT NULL AND char_length(resolution_note)>=5)
 )
);
CREATE INDEX order_cases_status_queue ON shamaa_app.order_cases(status,updated_at,id);

CREATE TABLE shamaa_app.order_case_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 case_id BIGINT NOT NULL REFERENCES shamaa_app.order_cases(id) ON DELETE RESTRICT,
 actor_id BIGINT NOT NULL REFERENCES shamaa_app.users(id) ON DELETE RESTRICT,
 actor_role TEXT NOT NULL CHECK(actor_role IN ('buyer','seller','admin')),
 event_type TEXT NOT NULL CHECK(event_type IN ('opened','buyer_message','seller_response','admin_resolved','admin_rejected')),
 body TEXT NOT NULL CHECK(char_length(body) BETWEEN 1 AND 3000),
 created_at BIGINT NOT NULL
);
CREATE INDEX order_case_events_timeline ON shamaa_app.order_case_events(case_id,id);

CREATE OR REPLACE FUNCTION shamaa_app.validate_order_case_event()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER
SET search_path=pg_catalog,shamaa_app AS $$
BEGIN
 IF NOT (
   (NEW.actor_role='buyer' AND NEW.event_type IN ('opened','buyer_message')
    AND EXISTS(SELECT 1 FROM shamaa_app.order_cases c WHERE c.id=NEW.case_id AND c.buyer_id=NEW.actor_id))
   OR
   (NEW.actor_role='seller' AND NEW.event_type='seller_response'
    AND EXISTS(SELECT 1 FROM shamaa_app.order_cases c WHERE c.id=NEW.case_id AND c.seller_id=NEW.actor_id))
   OR
   (NEW.actor_role='admin' AND NEW.event_type IN ('admin_resolved','admin_rejected')
    AND EXISTS(SELECT 1 FROM shamaa_app.users u WHERE u.id=NEW.actor_id AND u.role='admin' AND u.active=TRUE))
 ) THEN
   RAISE EXCEPTION 'case event actor is not authorized' USING ERRCODE='42501';
 END IF;
 RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION shamaa_app.reject_order_case_event_change()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER
SET search_path=pg_catalog,shamaa_app AS $$
BEGIN
 RAISE EXCEPTION 'case event history is append-only';
END;
$$;

CREATE OR REPLACE FUNCTION shamaa_app.reject_order_case_content_change()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER
SET search_path=pg_catalog,shamaa_app AS $$
BEGIN
 RAISE EXCEPTION 'case identity and opening evidence are immutable';
END;
$$;

CREATE OR REPLACE FUNCTION shamaa_app.require_order_case_transition()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER
SET search_path=pg_catalog,shamaa_app AS $$
DECLARE latest shamaa_app.order_case_events%ROWTYPE;
BEGIN
 IF NEW.status=OLD.status THEN RETURN NEW; END IF;
 SELECT * INTO latest FROM shamaa_app.order_case_events
  WHERE case_id=OLD.id ORDER BY id DESC LIMIT 1;

 IF OLD.status='open' AND NEW.status='seller_responded'
    AND latest.actor_id=OLD.seller_id AND latest.actor_role='seller'
    AND latest.event_type='seller_response' AND latest.created_at=NEW.updated_at THEN
   RETURN NEW;
 ELSIF OLD.status='seller_responded' AND NEW.status='open'
    AND latest.actor_id=OLD.buyer_id AND latest.actor_role='buyer'
    AND latest.event_type='buyer_message' AND latest.created_at=NEW.updated_at THEN
   RETURN NEW;
 ELSIF OLD.status IN ('open','seller_responded') AND NEW.status IN ('resolved','rejected')
    AND NEW.closed_by IS NOT NULL AND NEW.closed_at=NEW.updated_at
    AND EXISTS(SELECT 1 FROM shamaa_app.users u
                WHERE u.id=NEW.closed_by AND u.role='admin' AND u.active=TRUE)
    AND latest.actor_id=NEW.closed_by AND latest.actor_role='admin'
    AND latest.event_type=(CASE NEW.status WHEN 'resolved' THEN 'admin_resolved' ELSE 'admin_rejected' END)
    AND latest.created_at=NEW.closed_at AND latest.body=NEW.resolution_note THEN
   RETURN NEW;
 END IF;
 RAISE EXCEPTION 'invalid case status transition' USING ERRCODE='42501';
END;
$$;

CREATE TRIGGER order_case_event_authority
 BEFORE INSERT ON shamaa_app.order_case_events
 FOR EACH ROW EXECUTE FUNCTION shamaa_app.validate_order_case_event();
CREATE TRIGGER order_case_events_immutable_update
 BEFORE UPDATE ON shamaa_app.order_case_events
 FOR EACH ROW EXECUTE FUNCTION shamaa_app.reject_order_case_event_change();
CREATE TRIGGER order_case_events_immutable_delete
 BEFORE DELETE ON shamaa_app.order_case_events
 FOR EACH ROW EXECUTE FUNCTION shamaa_app.reject_order_case_event_change();
CREATE TRIGGER order_case_content_immutable
 BEFORE UPDATE OF seller_order_id,buyer_id,seller_id,reason,description,opened_at,response_due_at
 ON shamaa_app.order_cases
 FOR EACH ROW EXECUTE FUNCTION shamaa_app.reject_order_case_content_change();
CREATE TRIGGER order_case_status_guard
 BEFORE UPDATE OF status ON shamaa_app.order_cases
 FOR EACH ROW EXECUTE FUNCTION shamaa_app.require_order_case_transition();

ALTER TABLE shamaa_app.order_cases ENABLE ROW LEVEL SECURITY;
ALTER TABLE shamaa_app.order_cases FORCE ROW LEVEL SECURITY;
ALTER TABLE shamaa_app.order_case_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE shamaa_app.order_case_events FORCE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE shamaa_app.order_cases FROM PUBLIC;
REVOKE ALL ON TABLE shamaa_app.order_case_events FROM PUBLIC;
REVOKE ALL ON FUNCTION shamaa_app.validate_order_case_event() FROM PUBLIC;
REVOKE ALL ON FUNCTION shamaa_app.reject_order_case_event_change() FROM PUBLIC;
REVOKE ALL ON FUNCTION shamaa_app.reject_order_case_content_change() FROM PUBLIC;
REVOKE ALL ON FUNCTION shamaa_app.require_order_case_transition() FROM PUBLIC;

COMMIT;
