-- SHAM'A phase 2, batch 6: private shipment-case evidence images.
BEGIN;

CREATE TABLE shamaa_app.order_case_attachments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 case_id BIGINT NOT NULL REFERENCES shamaa_app.order_cases(id) ON DELETE RESTRICT,
 uploader_id BIGINT NOT NULL REFERENCES shamaa_app.users(id) ON DELETE RESTRICT,
 uploader_role TEXT NOT NULL CHECK(uploader_role IN ('buyer','seller')),
 storage_key TEXT NOT NULL UNIQUE CHECK(storage_key ~ '^[0-9a-f]{64}$'),
 content_type TEXT NOT NULL CHECK(content_type='image/webp'),
 bytes BIGINT NOT NULL CHECK(bytes BETWEEN 1 AND 5242880),
 digest TEXT NOT NULL CHECK(digest ~ '^[0-9a-f]{64}$'),
 created_at BIGINT NOT NULL,
 UNIQUE(case_id,digest)
);
CREATE INDEX order_case_attachments_timeline ON shamaa_app.order_case_attachments(case_id,id);

CREATE OR REPLACE FUNCTION shamaa_app.validate_order_case_attachment()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER
SET search_path=pg_catalog,shamaa_app AS $$
BEGIN
 IF NOT EXISTS (
   SELECT 1 FROM shamaa_app.order_cases c
   JOIN shamaa_app.users u ON u.id=NEW.uploader_id
   WHERE c.id=NEW.case_id AND c.status IN ('open','seller_responded')
     AND u.active=TRUE AND u.email_verified_at IS NOT NULL
     AND (
       (NEW.uploader_role='buyer' AND c.buyer_id=NEW.uploader_id)
       OR
       (NEW.uploader_role='seller' AND c.seller_id=NEW.uploader_id)
     )
 ) THEN
   RAISE EXCEPTION 'case attachment uploader is not an active verified participant'
     USING ERRCODE='42501';
 END IF;
 RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION shamaa_app.reject_order_case_attachment_change()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER
SET search_path=pg_catalog,shamaa_app AS $$
BEGIN
 RAISE EXCEPTION 'case attachment evidence is immutable';
END;
$$;

CREATE TRIGGER order_case_attachment_authority
 BEFORE INSERT ON shamaa_app.order_case_attachments
 FOR EACH ROW EXECUTE FUNCTION shamaa_app.validate_order_case_attachment();
CREATE TRIGGER order_case_attachments_immutable_update
 BEFORE UPDATE ON shamaa_app.order_case_attachments
 FOR EACH ROW EXECUTE FUNCTION shamaa_app.reject_order_case_attachment_change();
CREATE TRIGGER order_case_attachments_immutable_delete
 BEFORE DELETE ON shamaa_app.order_case_attachments
 FOR EACH ROW EXECUTE FUNCTION shamaa_app.reject_order_case_attachment_change();

ALTER TABLE shamaa_app.order_case_attachments ENABLE ROW LEVEL SECURITY;
ALTER TABLE shamaa_app.order_case_attachments FORCE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE shamaa_app.order_case_attachments FROM PUBLIC;
REVOKE ALL ON FUNCTION shamaa_app.validate_order_case_attachment() FROM PUBLIC;
REVOKE ALL ON FUNCTION shamaa_app.reject_order_case_attachment_change() FROM PUBLIC;

COMMIT;
