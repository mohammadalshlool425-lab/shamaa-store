-- SHAM'A phase 2, batch 7: controlled item-level return requests.
BEGIN;

CREATE TABLE shamaa_app.return_requests (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_item_id BIGINT NOT NULL REFERENCES shamaa_app.order_items(id) ON DELETE RESTRICT,
 seller_order_id BIGINT NOT NULL REFERENCES shamaa_app.seller_orders(id) ON DELETE RESTRICT,
 buyer_id BIGINT NOT NULL REFERENCES shamaa_app.users(id) ON DELETE RESTRICT,
 seller_id BIGINT NOT NULL REFERENCES shamaa_app.users(id) ON DELETE RESTRICT,
 quantity INTEGER NOT NULL CHECK(quantity BETWEEN 1 AND 99),
 reason TEXT NOT NULL CHECK(reason IN ('damaged','wrong_item','missing_item','not_as_described','changed_mind','other')),
 description TEXT NOT NULL CHECK(char_length(description) BETWEEN 20 AND 2000),
 status TEXT NOT NULL DEFAULT 'requested'
   CHECK(status IN ('requested','approved','rejected','return_shipped','received','resolved','cancelled')),
 requested_at BIGINT NOT NULL,
 response_due_at BIGINT NOT NULL,
 updated_at BIGINT NOT NULL,
 seller_note TEXT NOT NULL DEFAULT '',
 return_carrier TEXT NOT NULL DEFAULT '',
 return_tracking_number TEXT NOT NULL DEFAULT '',
 closed_at BIGINT,
 closed_by BIGINT REFERENCES shamaa_app.users(id) ON DELETE RESTRICT,
 decision_note TEXT NOT NULL DEFAULT '',
 CHECK(response_due_at>=requested_at),
 CHECK(
   (return_carrier='' AND return_tracking_number='')
   OR (char_length(return_carrier) BETWEEN 2 AND 50 AND char_length(return_tracking_number) BETWEEN 3 AND 100)
 ),
 CHECK(
   (status IN ('return_shipped','received','resolved') AND return_carrier<>'' AND return_tracking_number<>'')
   OR status NOT IN ('return_shipped','received','resolved')
 ),
 CHECK(
   (status IN ('rejected','resolved','cancelled') AND closed_at IS NOT NULL AND closed_by IS NOT NULL AND char_length(decision_note)>=5)
   OR
   (status NOT IN ('rejected','resolved','cancelled') AND closed_at IS NULL AND closed_by IS NULL AND decision_note='')
 )
);
CREATE INDEX return_requests_buyer_queue ON shamaa_app.return_requests(buyer_id,status,updated_at,id);
CREATE INDEX return_requests_seller_queue ON shamaa_app.return_requests(seller_id,status,updated_at,id);
CREATE INDEX return_requests_item_history ON shamaa_app.return_requests(order_item_id,id);
CREATE UNIQUE INDEX one_active_return_per_order_item ON shamaa_app.return_requests(order_item_id)
 WHERE status IN ('requested','approved','return_shipped','received');

CREATE TABLE shamaa_app.return_request_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 request_id BIGINT NOT NULL REFERENCES shamaa_app.return_requests(id) ON DELETE RESTRICT,
 actor_id BIGINT NOT NULL REFERENCES shamaa_app.users(id) ON DELETE RESTRICT,
 actor_role TEXT NOT NULL CHECK(actor_role IN ('buyer','seller','admin')),
 event_type TEXT NOT NULL CHECK(event_type IN (
   'opened','seller_approved','seller_rejected','buyer_cancelled',
   'buyer_return_shipped','seller_received','admin_resolved','admin_rejected'
 )),
 body TEXT NOT NULL CHECK(char_length(body) BETWEEN 1 AND 2000),
 created_at BIGINT NOT NULL
);
CREATE INDEX return_request_events_timeline ON shamaa_app.return_request_events(request_id,id);

CREATE OR REPLACE FUNCTION shamaa_app.guard_return_purchase()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER
SET search_path=pg_catalog,shamaa_app AS $
DECLARE
 purchased shamaa_app.order_items%ROWTYPE;
 eligible boolean;
 already_returned integer;
BEGIN
 SELECT oi.* INTO purchased
   FROM shamaa_app.order_items oi
   JOIN shamaa_app.seller_orders so ON so.id=oi.seller_order_id
   JOIN shamaa_app.orders o ON o.id=so.order_id
   JOIN shamaa_app.stores s ON s.id=so.store_id
   JOIN shamaa_app.users buyer ON buyer.id=o.buyer_id
   JOIN shamaa_app.users seller ON seller.id=s.owner_id
  WHERE oi.id=NEW.order_item_id
    AND oi.seller_order_id=NEW.seller_order_id
    AND o.buyer_id=NEW.buyer_id
    AND s.owner_id=NEW.seller_id
    AND so.status='delivered'
    AND buyer.active=TRUE AND buyer.email_verified_at IS NOT NULL
    AND seller.active=TRUE
  FOR UPDATE OF oi;
 IF NOT FOUND THEN
  RAISE EXCEPTION 'return request must match a delivered item owned by the buyer and store'
    USING ERRCODE='42501';
 END IF;

 SELECT EXISTS(
   SELECT 1 FROM shamaa_app.order_events e
    WHERE e.seller_order_id=NEW.seller_order_id AND e.to_status='delivered'
      AND e.created_at<=NEW.requested_at
      AND NEW.requested_at-e.created_at BETWEEN 0 AND 1209600
 ) INTO eligible;
 IF NOT eligible THEN
  RAISE EXCEPTION 'return request is outside the delivered-item window'
    USING ERRCODE='42501';
 END IF;

 SELECT COALESCE(SUM(r.quantity),0) INTO already_returned
   FROM shamaa_app.return_requests r
  WHERE r.order_item_id=NEW.order_item_id
    AND r.status IN ('requested','approved','return_shipped','received','resolved');
 IF already_returned+NEW.quantity>purchased.quantity THEN
  RAISE EXCEPTION 'return quantity exceeds purchased quantity'
    USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END;
$;

CREATE TRIGGER return_request_purchase_guard
 BEFORE INSERT ON shamaa_app.return_requests FOR EACH ROW
 EXECUTE FUNCTION shamaa_app.guard_return_purchase();

CREATE OR REPLACE FUNCTION shamaa_app.guard_return_initial_state()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER
SET search_path=pg_catalog,shamaa_app AS $
BEGIN
 IF NEW.status<>'requested' THEN
  RAISE EXCEPTION 'a return request must be created in requested state';
 END IF;
 RETURN NEW;
END;
$;

CREATE OR REPLACE FUNCTION shamaa_app.guard_return_terminal_immutable()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER
SET search_path=pg_catalog,shamaa_app AS $
BEGIN
 IF OLD.status IN ('rejected','resolved','cancelled') THEN
  RAISE EXCEPTION 'a terminal return request is immutable';
 END IF;
 RETURN NEW;
END;
$;

CREATE OR REPLACE FUNCTION shamaa_app.validate_return_request_event()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER
SET search_path=pg_catalog,shamaa_app AS $$
BEGIN
 IF NOT (
  (NEW.actor_role='buyer' AND NEW.event_type IN ('opened','buyer_cancelled','buyer_return_shipped')
   AND EXISTS(SELECT 1 FROM shamaa_app.return_requests r WHERE r.id=NEW.request_id AND r.buyer_id=NEW.actor_id
     AND ((NEW.event_type='opened' AND r.status='requested')
       OR (NEW.event_type='buyer_cancelled' AND r.status IN ('requested','approved'))
       OR (NEW.event_type='buyer_return_shipped' AND r.status='approved'))))
  OR
  (NEW.actor_role='seller' AND NEW.event_type IN ('seller_approved','seller_rejected','seller_received')
   AND EXISTS(SELECT 1 FROM shamaa_app.return_requests r WHERE r.id=NEW.request_id AND r.seller_id=NEW.actor_id
     AND ((NEW.event_type IN ('seller_approved','seller_rejected') AND r.status='requested')
       OR (NEW.event_type='seller_received' AND r.status='return_shipped'))))
  OR
  (NEW.actor_role='admin' AND NEW.event_type IN ('admin_resolved','admin_rejected')
   AND EXISTS(SELECT 1 FROM shamaa_app.users u WHERE u.id=NEW.actor_id AND u.role='admin' AND u.active=TRUE))
 ) THEN
  RAISE EXCEPTION 'return event actor is not authorized' USING ERRCODE='42501';
 END IF;
 RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION shamaa_app.reject_return_event_change()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER
SET search_path=pg_catalog,shamaa_app AS $$
BEGIN RAISE EXCEPTION 'return request event history is append-only'; END;
$$;

CREATE OR REPLACE FUNCTION shamaa_app.reject_return_identity_change()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER
SET search_path=pg_catalog,shamaa_app AS $$
BEGIN RAISE EXCEPTION 'return request identity and opening evidence are immutable'; END;
$$;

CREATE OR REPLACE FUNCTION shamaa_app.guard_return_seller_note()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER
SET search_path=pg_catalog,shamaa_app AS $$
BEGIN
 IF NEW.seller_note<>OLD.seller_note AND NOT (OLD.status='requested' AND NEW.status IN ('approved','rejected')) THEN
  RAISE EXCEPTION 'seller response note can only be set with the seller decision';
 END IF;
 RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION shamaa_app.guard_return_tracking()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER
SET search_path=pg_catalog,shamaa_app AS $$
BEGIN
 IF (NEW.return_carrier<>OLD.return_carrier OR NEW.return_tracking_number<>OLD.return_tracking_number)
  AND NOT (OLD.status='approved' AND NEW.status='return_shipped'
           AND OLD.return_carrier='' AND OLD.return_tracking_number=''
           AND NEW.return_carrier<>'' AND NEW.return_tracking_number<>'') THEN
  RAISE EXCEPTION 'return tracking can only be set when the buyer ships the return';
 END IF;
 RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION shamaa_app.guard_return_status()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER
SET search_path=pg_catalog,shamaa_app AS $$
DECLARE latest shamaa_app.return_request_events%ROWTYPE;
BEGIN
 IF NEW.status=OLD.status THEN RETURN NEW; END IF;
 SELECT * INTO latest FROM shamaa_app.return_request_events
  WHERE request_id=OLD.id ORDER BY id DESC LIMIT 1;

 IF OLD.status='requested' AND NEW.status='approved'
  AND latest.actor_id=OLD.seller_id AND latest.actor_role='seller'
  AND latest.event_type='seller_approved' AND latest.created_at=NEW.updated_at THEN
  RETURN NEW;
 ELSIF OLD.status='requested' AND NEW.status='rejected'
  AND NEW.closed_by=OLD.seller_id AND NEW.closed_at=NEW.updated_at
  AND char_length(NEW.decision_note)>=5
  AND latest.actor_id=OLD.seller_id AND latest.actor_role='seller'
  AND latest.event_type='seller_rejected' AND latest.created_at=NEW.closed_at
  AND latest.body=NEW.decision_note THEN
  RETURN NEW;
 ELSIF OLD.status IN ('requested','approved') AND NEW.status='cancelled'
  AND NEW.closed_by=OLD.buyer_id AND NEW.closed_at=NEW.updated_at
  AND char_length(NEW.decision_note)>=5
  AND latest.actor_id=OLD.buyer_id AND latest.actor_role='buyer'
  AND latest.event_type='buyer_cancelled' AND latest.created_at=NEW.closed_at
  AND latest.body=NEW.decision_note THEN
  RETURN NEW;
 ELSIF OLD.status='approved' AND NEW.status='return_shipped'
  AND NEW.return_carrier<>'' AND NEW.return_tracking_number<>''
  AND latest.actor_id=OLD.buyer_id AND latest.actor_role='buyer'
  AND latest.event_type='buyer_return_shipped' AND latest.created_at=NEW.updated_at THEN
  RETURN NEW;
 ELSIF OLD.status='return_shipped' AND NEW.status='received'
  AND latest.actor_id=OLD.seller_id AND latest.actor_role='seller'
  AND latest.event_type='seller_received' AND latest.created_at=NEW.updated_at THEN
  RETURN NEW;
 ELSIF OLD.status IN ('requested','approved','return_shipped','received')
  AND NEW.status IN ('resolved','rejected')
  AND NEW.closed_by IS NOT NULL AND NEW.closed_at=NEW.updated_at
  AND char_length(NEW.decision_note)>=5
  AND EXISTS(SELECT 1 FROM shamaa_app.users u WHERE u.id=NEW.closed_by AND u.role='admin' AND u.active=TRUE)
  AND latest.actor_id=NEW.closed_by AND latest.actor_role='admin'
  AND latest.event_type=CASE NEW.status WHEN 'resolved' THEN 'admin_resolved' ELSE 'admin_rejected' END
  AND latest.created_at=NEW.closed_at AND latest.body=NEW.decision_note THEN
  RETURN NEW;
 END IF;
 RAISE EXCEPTION 'invalid return request status transition' USING ERRCODE='42501';
END;
$$;

