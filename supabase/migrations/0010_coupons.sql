-- SHAM'A phase 2, batch 8: store-funded, single-store coupon redemption.
BEGIN;

ALTER TABLE shamaa_app.orders
 ADD COLUMN discount_fils BIGINT NOT NULL DEFAULT 0
 CHECK(discount_fils>=0 AND discount_fils<=total_fils);
ALTER TABLE shamaa_app.seller_orders
 ADD COLUMN discount_fils BIGINT NOT NULL DEFAULT 0
 CHECK(discount_fils>=0 AND discount_fils<=subtotal_fils);

CREATE TABLE shamaa_app.coupons (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 store_id BIGINT NOT NULL REFERENCES shamaa_app.stores(id) ON DELETE RESTRICT,
 code TEXT NOT NULL UNIQUE CHECK(code ~ '^[A-Z0-9][A-Z0-9_-]{2,31}$'),
 discount_type TEXT NOT NULL CHECK(discount_type IN ('percent','fixed')),
 discount_value BIGINT NOT NULL CHECK(
   (discount_type='percent' AND discount_value BETWEEN 1 AND 10000)
   OR (discount_type='fixed' AND discount_value BETWEEN 1 AND 100000000000)
 ),
 minimum_subtotal_fils BIGINT NOT NULL DEFAULT 0 CHECK(minimum_subtotal_fils>=0),
 maximum_discount_fils BIGINT CHECK(maximum_discount_fils IS NULL OR maximum_discount_fils>0),
 starts_at BIGINT,
 expires_at BIGINT,
 max_uses BIGINT CHECK(max_uses IS NULL OR max_uses>=1),
 max_uses_per_buyer INTEGER NOT NULL DEFAULT 1 CHECK(max_uses_per_buyer BETWEEN 1 AND 100),
 used_count BIGINT NOT NULL DEFAULT 0 CHECK(used_count>=0 AND (max_uses IS NULL OR used_count<=max_uses)),
 active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at BIGINT NOT NULL,
 updated_at BIGINT NOT NULL,
 CHECK(starts_at IS NULL OR starts_at>=0),
 CHECK(expires_at IS NULL OR expires_at>=0),
 CHECK(expires_at IS NULL OR starts_at IS NULL OR expires_at>starts_at)
);
CREATE INDEX coupons_store ON shamaa_app.coupons(store_id,active,created_at);

CREATE TABLE shamaa_app.coupon_redemptions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 coupon_id BIGINT NOT NULL REFERENCES shamaa_app.coupons(id) ON DELETE RESTRICT,
 order_id BIGINT NOT NULL UNIQUE REFERENCES shamaa_app.orders(id) ON DELETE RESTRICT,
 seller_order_id BIGINT NOT NULL UNIQUE REFERENCES shamaa_app.seller_orders(id) ON DELETE RESTRICT,
 store_id BIGINT NOT NULL REFERENCES shamaa_app.stores(id) ON DELETE RESTRICT,
 buyer_id BIGINT NOT NULL REFERENCES shamaa_app.users(id) ON DELETE RESTRICT,
 code TEXT NOT NULL,
 discount_fils BIGINT NOT NULL CHECK(discount_fils>0),
 redeemed_at BIGINT NOT NULL,
 UNIQUE(coupon_id,buyer_id,order_id)
);
CREATE INDEX coupon_redemptions_buyer ON shamaa_app.coupon_redemptions(coupon_id,buyer_id,id);
CREATE INDEX coupon_redemptions_store ON shamaa_app.coupon_redemptions(store_id,id);

CREATE OR REPLACE FUNCTION shamaa_app.guard_coupon_redemption()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER
SET search_path=pg_catalog,shamaa_app AS $$
DECLARE
 coupon_row shamaa_app.coupons%ROWTYPE;
 existing_uses BIGINT;
BEGIN
 SELECT * INTO coupon_row FROM shamaa_app.coupons
  WHERE id=NEW.coupon_id AND store_id=NEW.store_id
  FOR UPDATE;
 IF NOT FOUND THEN
  RAISE EXCEPTION 'coupon redemption references an unknown store coupon'
   USING ERRCODE='42501';
 END IF;
 SELECT count(*) INTO existing_uses FROM shamaa_app.coupon_redemptions
  WHERE coupon_id=NEW.coupon_id AND buyer_id=NEW.buyer_id;
 IF coupon_row.used_count<1
    OR (coupon_row.max_uses IS NOT NULL AND coupon_row.used_count>coupon_row.max_uses)
    OR existing_uses>=coupon_row.max_uses_per_buyer
    OR coupon_row.code<>NEW.code
    OR NOT EXISTS (
      SELECT 1
        FROM shamaa_app.orders o
        JOIN shamaa_app.seller_orders so ON so.id=NEW.seller_order_id
       WHERE o.id=NEW.order_id
         AND o.buyer_id=NEW.buyer_id
         AND o.discount_fils=NEW.discount_fils
         AND so.order_id=o.id
         AND so.store_id=NEW.store_id
         AND so.discount_fils=NEW.discount_fils
         AND NEW.discount_fils<=so.subtotal_fils
    ) THEN
  RAISE EXCEPTION 'coupon redemption does not match the order or usage limits'
   USING ERRCODE='42501';
 END IF;
 RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION shamaa_app.reject_coupon_redemption_change()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER
SET search_path=pg_catalog,shamaa_app AS $$
BEGIN
 RAISE EXCEPTION 'coupon redemptions are immutable' USING ERRCODE='42501';
END;
$$;

CREATE TRIGGER coupon_redemption_guard
 BEFORE INSERT ON shamaa_app.coupon_redemptions FOR EACH ROW
 EXECUTE FUNCTION shamaa_app.guard_coupon_redemption();
CREATE TRIGGER coupon_redemptions_immutable_update
 BEFORE UPDATE ON shamaa_app.coupon_redemptions FOR EACH ROW
 EXECUTE FUNCTION shamaa_app.reject_coupon_redemption_change();
CREATE TRIGGER coupon_redemptions_immutable_delete
 BEFORE DELETE ON shamaa_app.coupon_redemptions FOR EACH ROW
 EXECUTE FUNCTION shamaa_app.reject_coupon_redemption_change();

ALTER TABLE shamaa_app.coupons ENABLE ROW LEVEL SECURITY;
ALTER TABLE shamaa_app.coupons FORCE ROW LEVEL SECURITY;
ALTER TABLE shamaa_app.coupon_redemptions ENABLE ROW LEVEL SECURITY;
ALTER TABLE shamaa_app.coupon_redemptions FORCE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE shamaa_app.coupons FROM PUBLIC;
REVOKE ALL ON TABLE shamaa_app.coupon_redemptions FROM PUBLIC;
REVOKE ALL ON FUNCTION shamaa_app.guard_coupon_redemption() FROM PUBLIC;
REVOKE ALL ON FUNCTION shamaa_app.reject_coupon_redemption_change() FROM PUBLIC;

COMMIT;
