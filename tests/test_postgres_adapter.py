"""Live PostgreSQL adapter contract tests; skipped outside the PostgreSQL CI job."""
import os

import pytest


def test_psycopg_adapter_executes_portable_contract_against_postgresql():
    conninfo = os.getenv("SHAMAA_TEST_DATABASE_URL")
    if not conninfo:
        pytest.skip("PostgreSQL adapter integration test requires SHAMAA_TEST_DATABASE_URL")

    import psycopg
    from server.database import DatabaseIntegrityError, insert_id
    from server.postgres_database import PostgresDatabase

    db = PostgresDatabase(conninfo)
    assert db.schema_version() == 3
    db.initialize()

    # This table is test-only and is removed even if an assertion fails.
    with psycopg.connect(conninfo, autocommit=True) as admin:
        admin.execute(
            """
            CREATE TABLE IF NOT EXISTS shamaa_app.adapter_contract_rows (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                value TEXT NOT NULL UNIQUE
            )
            """
        )
        admin.execute("TRUNCATE shamaa_app.adapter_contract_rows RESTART IDENTITY")

    try:
        with db.transaction() as connection:
            first_id = insert_id(
                connection,
                "INSERT INTO adapter_contract_rows(value) VALUES(?)",
                ("committed",),
            )
            assert first_id == 1
            changed = connection.execute(
                "UPDATE adapter_contract_rows SET value=? WHERE id=?",
                ("updated", first_id),
            )
            assert changed.rowcount == 1

        with db.read() as connection:
            row = connection.execute(
                "SELECT id, value FROM adapter_contract_rows WHERE id=?",
                (first_id,),
            ).fetchone()
            assert row["id"] == first_id
            assert row[0] == first_id
            assert dict(row) == {"id": first_id, "value": "updated"}
            assert connection.execute(
                "SELECT '?' AS literal, ? AS bound",
                (42,),
            ).fetchone()["bound"] == 42

        with pytest.raises(RuntimeError, match="force rollback"):
            with db.transaction() as connection:
                insert_id(
                    connection,
                    "INSERT INTO adapter_contract_rows(value) VALUES(?)",
                    ("rolled-back",),
                )
                raise RuntimeError("force rollback")

        with db.read() as connection:
            assert connection.execute(
                "SELECT COUNT(*) FROM adapter_contract_rows WHERE value=?",
                ("rolled-back",),
            ).fetchone()[0] == 0

        with pytest.raises(DatabaseIntegrityError):
            with db.transaction() as connection:
                connection.execute(
                    "INSERT INTO adapter_contract_rows(value) VALUES(?)",
                    ("updated",),
                )
    finally:
        with psycopg.connect(conninfo, autocommit=True) as admin:
            admin.execute("DROP TABLE IF EXISTS shamaa_app.adapter_contract_rows")


def test_postgres_adapter_rejects_unsafe_configuration():
    conninfo = os.getenv("SHAMAA_TEST_DATABASE_URL")
    if not conninfo:
        pytest.skip("PostgreSQL adapter integration test requires SHAMAA_TEST_DATABASE_URL")
    from server.postgres_database import PostgresDatabase

    with pytest.raises(ValueError):
        PostgresDatabase(conninfo, schema="shamaa_app; DROP SCHEMA public")
    with pytest.raises(ValueError):
        PostgresDatabase("sqlite:///not-postgres")
