def test_user_scoped_adapter_sets_identity_only_for_each_transaction():
    conninfo = os.getenv("SHAMAA_TEST_DATABASE_URL")
    if not conninfo:
        pytest.skip("PostgreSQL adapter integration test requires SHAMAA_TEST_DATABASE_URL")

    from server.postgres_database import PostgresDatabase

    db = PostgresDatabase(conninfo)
    scoped = db.for_user(4242)

    with scoped.read() as connection:
        assert connection.execute(
            "SELECT current_setting('app.current_user_id', TRUE)"
        ).fetchone()[0] == "4242"

    # A fresh unscoped connection must not inherit the previous request identity.
    with db.read() as connection:
        assert connection.execute(
            "SELECT current_setting('app.current_user_id', TRUE)"
        ).fetchone()[0] is None

    # The setting is also cleared after a transaction exits exceptionally.
    with pytest.raises(RuntimeError, match="rollback identity"):
        with scoped.transaction() as connection:
            assert connection.execute(
                "SELECT current_setting('app.current_user_id', TRUE)"
            ).fetchone()[0] == "4242"
            raise RuntimeError("rollback identity")

    with db.read() as connection:
        assert connection.execute(
            "SELECT current_setting('app.current_user_id', TRUE)"
        ).fetchone()[0] is None



def test_postgres_request_scope_binds_session_then_verified_user_and_resets():
    conninfo = os.getenv("SHAMAA_TEST_DATABASE_URL")
    if not conninfo:
        pytest.skip("PostgreSQL request identity test requires SHAMAA_TEST_DATABASE_URL")

    from server.postgres_database import PostgresDatabase

    db = PostgresDatabase(conninfo)
    session_hash = "a" * 64

    with db.request_scope(session_hash) as bind_user:
        with db.read() as connection:
            row = connection.execute(
                "SELECT current_setting('app.session_token_hash', TRUE), "
                "current_setting('app.current_user_id', TRUE)"
            ).fetchone()
            assert row[0] == session_hash
            assert row[1] is None

        bind_user(4242)
        with db.transaction() as connection:
            row = connection.execute(
                "SELECT current_setting('app.session_token_hash', TRUE), "
                "current_setting('app.current_user_id', TRUE)"
            ).fetchone()
            assert row[0] == session_hash
            assert row[1] == "4242"

    with db.read() as connection:
        row = connection.execute(
            "SELECT current_setting('app.session_token_hash', TRUE), "
            "current_setting('app.current_user_id', TRUE)"
        ).fetchone()
        assert row[0] is None
        assert row[1] is None


def test_postgres_system_operation_is_allowlisted_transaction_local_and_reset():
    conninfo = os.getenv("SHAMAA_TEST_DATABASE_URL")
    if not conninfo:
        pytest.skip("PostgreSQL system operation test requires SHAMAA_TEST_DATABASE_URL")

    from server.postgres_database import PostgresDatabase

    db = PostgresDatabase(conninfo)
    with pytest.raises(ValueError, match="Unsupported PostgreSQL system operation"):
        with db.system_operation("auth.arbitrary"):
            pass

    with db.system_operation("auth.register"):
        with db.read() as connection:
            assert connection.execute(
                "SELECT current_setting('app.system_operation', TRUE)"
            ).fetchone()[0] == "auth.register"
        with pytest.raises(RuntimeError, match="Cannot nest different"):
            with db.system_operation("auth.login"):
                pass
        with db.system_operation("auth.register"):
            with db.transaction() as connection:
                assert connection.execute(
                    "SELECT current_setting('app.system_operation', TRUE)"
                ).fetchone()[0] == "auth.register"

    # Transaction-local settings and ContextVar scope must both be cleared.
    with db.read() as connection:
        assert connection.execute(
            "SELECT current_setting('app.system_operation', TRUE)"
        ).fetchone()[0] is None

    # Exceptional exits restore the previous operation context as well.
    with pytest.raises(RuntimeError, match="abort operation"):
        with db.system_operation("auth.reset_password"):
            with db.read() as connection:
                assert connection.execute(
                    "SELECT current_setting('app.system_operation', TRUE)"
                ).fetchone()[0] == "auth.reset_password"
            raise RuntimeError("abort operation")
    with db.read() as connection:
        assert connection.execute(
            "SELECT current_setting('app.system_operation', TRUE)"
        ).fetchone()[0] is None
